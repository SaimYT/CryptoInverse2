def _generate():
    rnd = random.Random(42)
    reviews = []
    for i in range(2143):
        name = rnd.choice(_NAMES)
        stars = rnd.choices([4, 5], weights=[20, 80])[0]
        template = rnd.choice(_REVIEW_TEMPLATES)
        amount = rnd.choice([
            "15к", "25к", "30к", "50к", "60к", "75к", "80к",
            "100к", "120к", "150к", "180к", "200к", "250к",
            "300к", "500к", "1.000", "2.000", "5.000",
            "10.000", "20.000", "30.000", "50.000", "75.000",
            "100.000", "150.000", "200.000"
        ])
        text = template.replace("{amount}", amount)
        reviews.append({
            "id": i,
            "name": name,
            "stars": stars,
            "text": text
        })
    return reviews


REVIEWS = _generate()
TOTAL_REVIEWS = len(REVIEWS)


def get_review_by_id(review_id: int):
    if 0 <= review_id < TOTAL_REVIEWS:
        return REVIEWS[review_id]
    return None